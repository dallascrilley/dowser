#!/bin/bash

################################################################################
# Acuity Scheduling Manager - Setup Script
################################################################################
#
# Purpose: Initialize Acuity Scheduling Manager with all dependencies,
#          credential validation, and environment configuration
#
# Usage:
#   ./setup.sh                    # Interactive setup
#   ./setup.sh --verify-only      # Only verify credentials
#   ./setup.sh --skip-redis       # Skip Redis check
#
# Exit Codes:
#   0 - Setup successful
#   1 - Setup failed
#   2 - Invalid arguments
#
# Requirements:
#   - Python 3.8+
#   - pip
#   - .env file with credentials
#
# Features:
#   - Python dependency installation
#   - Credential validation (masks sensitive info)
#   - API connectivity test
#   - Redis availability check (optional)
#   - Directory structure verification
#   - Usage instructions
#
################################################################################

set -euo pipefail

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Configuration
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILL_DIR="$(dirname "$SCRIPT_DIR")"
ENV_FILE="${SKILL_DIR}/.env"
PYTHON_MIN_VERSION="3.8"

# Flags
VERIFY_ONLY=false
SKIP_REDIS=false
VERBOSE=false

# Counter for checks
CHECKS_PASSED=0
CHECKS_FAILED=0

################################################################################
# Functions
################################################################################

print_header() {
    echo -e "\n${BLUE}▶▶▶ $1 ${NC}\n"
}

print_success() {
    echo -e "${GREEN}✓ $1${NC}"
    ((CHECKS_PASSED++))
}

print_error() {
    echo -e "${RED}✗ $1${NC}"
    ((CHECKS_FAILED++))
}

print_warning() {
    echo -e "${YELLOW}⚠ $1${NC}"
}

print_info() {
    echo -e "${BLUE}ℹ $1${NC}"
}

mask_credential() {
    local credential="$1"
    if [ ${#credential} -le 8 ]; then
        echo "****"
    else
        local first_4="${credential:0:4}"
        local last_4="${credential: -4}"
        echo "${first_4}...${last_4}"
    fi
}

show_usage() {
    cat << EOF
${BLUE}Acuity Scheduling Manager - Setup Script${NC}

${BLUE}Usage:${NC}
  ./setup.sh [OPTIONS]

${BLUE}Options:${NC}
  --verify-only       Only verify credentials, skip installation
  --skip-redis        Skip Redis availability check
  --verbose           Show detailed output
  -h, --help          Show this help message

${BLUE}Examples:${NC}
  # Full setup with all checks
  ./setup.sh

  # Verify credentials only
  ./setup.sh --verify-only

  # Setup without Redis check
  ./setup.sh --skip-redis

${BLUE}Configuration:${NC}
  Environment variables should be set in: $ENV_FILE

  Required variables:
    ACUITY_USER_ID     Your Acuity User ID
    ACUITY_API_KEY     Your Acuity API Key

  Optional variables:
    ACUITY_WEBHOOK_URL Webhook endpoint URL
    REDIS_URL          Redis connection string (for caching)

EOF
}

check_python() {
    print_header "Checking Python Installation"

    if ! command -v python3 &> /dev/null; then
        print_error "Python 3 not found. Please install Python 3.8+ first."
        return 1
    fi

    PYTHON_VERSION=$(python3 -c 'import sys; print(".".join(map(str, sys.version_info[:2])))')
    print_info "Python version: $PYTHON_VERSION"

    # Check minimum version
    if python3 -c "import sys; sys.exit(0 if tuple(map(int, '$PYTHON_VERSION'.split('.'))) >= (3, 8) else 1)"; then
        print_success "Python version meets requirements (>= $PYTHON_MIN_VERSION)"
    else
        print_error "Python version is below $PYTHON_MIN_VERSION"
        return 1
    fi
}

check_environment_file() {
    print_header "Checking Environment File"

    if [ ! -f "$ENV_FILE" ]; then
        print_warning "Environment file not found: $ENV_FILE"
        print_info "Creating template .env file..."

        cat > "$ENV_FILE" << 'ENVTEMPLATE'
# Acuity Scheduling API Configuration
# Generated by setup.sh

# Required: Your Acuity API credentials
# Get these from: Business Settings > Integrations > API
ACUITY_USER_ID="your_user_id_here"
ACUITY_API_KEY="your_api_key_here"

# Optional: Webhook configuration
ACUITY_WEBHOOK_URL="https://your-domain.com/webhooks/acuity"
ACUITY_WEBHOOK_SECRET="your_webhook_secret"

# Optional: Redis configuration for caching
REDIS_URL="redis://localhost:6379/0"

# Optional: Logging configuration
LOG_LEVEL="INFO"
LOG_FILE="acuity_manager.log"

# Environment
ENVIRONMENT="development"
ENVTEMPLATE

        print_info "Created template at: $ENV_FILE"
        print_warning "Please edit this file with your actual credentials before running setup again"
        return 1
    fi

    print_success "Environment file found: $ENV_FILE"
}

load_credentials() {
    # Source the .env file (safely)
    if [ -f "$ENV_FILE" ]; then
        set -a
        source "$ENV_FILE"
        set +a
    fi
}

check_credentials() {
    print_header "Validating Credentials"

    if [ -z "${ACUITY_USER_ID:-}" ]; then
        print_error "ACUITY_USER_ID not set in environment"
        return 1
    fi

    if [ -z "${ACUITY_API_KEY:-}" ]; then
        print_error "ACUITY_API_KEY not set in environment"
        return 1
    fi

    print_success "Credentials found"
    print_info "User ID: $ACUITY_USER_ID"
    print_info "API Key: $(mask_credential "$ACUITY_API_KEY")"
}

install_dependencies() {
    print_header "Installing Python Dependencies"

    local dependencies=(
        "requests>=2.28.0"
        "python-dotenv>=0.21.0"
        "pydantic>=1.10.0"
        "pytz>=2023.3"
        "rich>=13.0.0"
    )

    # Check if pip is available
    if ! command -v pip3 &> /dev/null; then
        print_error "pip3 not found. Please install pip first."
        return 1
    fi

    print_info "Installing packages..."

    for package in "${dependencies[@]}"; do
        print_info "Installing $package..."
        if pip3 install --quiet "$package"; then
            print_success "Installed $package"
        else
            print_error "Failed to install $package"
            return 1
        fi
    done

    print_success "All dependencies installed successfully"
}

test_api_connectivity() {
    print_header "Testing Acuity API Connectivity"

    if [ -z "${ACUITY_USER_ID:-}" ] || [ -z "${ACUITY_API_KEY:-}" ]; then
        print_error "Credentials not loaded. Skipping API test."
        return 1
    fi

    print_info "Testing endpoint: GET /me"

    # Make API request
    local response=$(python3 -c "
import requests
import sys
from requests.auth import HTTPBasicAuth

try:
    response = requests.get(
        'https://acuityscheduling.com/api/v1/me',
        auth=HTTPBasicAuth('$ACUITY_USER_ID', '$ACUITY_API_KEY'),
        timeout=10
    )

    if response.status_code == 200:
        data = response.json()
        print(f\"Account: {data.get('name', 'Unknown')}\")
        print(f\"Email: {data.get('email', 'Unknown')}\")
        print(f\"Status: {response.status_code}\")
        sys.exit(0)
    elif response.status_code == 401:
        print('Error: Unauthorized (invalid credentials)')
        sys.exit(1)
    else:
        print(f'Error: HTTP {response.status_code}')
        print(response.text)
        sys.exit(1)
except Exception as e:
    print(f'Error: {e}')
    sys.exit(1)
" 2>&1)

    if [ $? -eq 0 ]; then
        print_success "API connectivity test passed"
        print_info "$response"
    else
        print_error "API connectivity test failed"
        print_error "$response"
        return 1
    fi
}

check_redis() {
    print_header "Checking Redis Availability (Optional)"

    if [ "$SKIP_REDIS" = true ]; then
        print_info "Redis check skipped"
        return 0
    fi

    local redis_url="${REDIS_URL:-redis://localhost:6379/0}"

    print_info "Testing Redis connection: $redis_url"

    local result=$(python3 -c "
import sys
try:
    import redis
    url = '$redis_url'
    r = redis.from_url(url, decode_responses=True)
    info = r.info()
    print(f'Connected. Redis version: {info.get(\"redis_version\", \"unknown\")}')
    sys.exit(0)
except ImportError:
    print('redis library not installed (optional)')
    sys.exit(0)
except Exception as e:
    print(f'Redis not available: {e}')
    sys.exit(1)
" 2>&1)

    if [ $? -eq 0 ]; then
        print_success "Redis check passed: $result"
    else
        print_warning "Redis not available (this is optional): $result"
    fi
}

verify_directory_structure() {
    print_header "Verifying Directory Structure"

    local required_dirs=(
        "$SKILL_DIR"
        "$SCRIPT_DIR"
    )

    for dir in "${required_dirs[@]}"; do
        if [ -d "$dir" ]; then
            print_success "Directory exists: $dir"
        else
            print_error "Directory not found: $dir"
            return 1
        fi
    done

    # List available scripts
    print_info "Available scripts in $SCRIPT_DIR:"
    if ls -1 "$SCRIPT_DIR"/*.py "$SCRIPT_DIR"/*.sh 2>/dev/null | head -10 | sed 's/^/  /' | grep -q '.'; then
        ls -1 "$SCRIPT_DIR"/*.py "$SCRIPT_DIR"/*.sh 2>/dev/null | head -10 | sed 's/^/  /'
    else
        print_warning "No scripts found yet"
    fi
}

show_summary() {
    local status="$1"

    print_header "Setup Summary"

    echo "Checks Passed: ${GREEN}$CHECKS_PASSED${NC}"
    echo "Checks Failed: ${RED}$CHECKS_FAILED${NC}"
    echo ""

    if [ "$status" = "success" ]; then
        print_success "Setup completed successfully!"
        echo ""
        echo "${BLUE}Next Steps:${NC}"
        echo "1. Verify your credentials are correct in: $ENV_FILE"
        echo "2. Review available scripts:"
        echo "   - validate_credentials.py   - Validate API access"
        echo "   - check_availability.py     - Check appointment availability"
        echo "   - create_appointment.py     - Create new appointments"
        echo "   - export_appointments.py    - Export appointments to CSV/JSON"
        echo "   - test_webhook.py           - Test webhook delivery"
        echo "   - sync_clients.py           - Sync clients to external system"
        echo ""
        echo "3. Run validation: python3 scripts/validate_credentials.py"
        echo ""
    else
        print_error "Setup completed with errors"
        echo ""
        echo "${YELLOW}Troubleshooting:${NC}"
        echo "- Check that .env file has correct credentials"
        echo "- Verify Python 3.8+ is installed"
        echo "- Review error messages above"
        echo ""
    fi
}

################################################################################
# Main Setup Flow
################################################################################

main() {
    # Parse arguments
    while [[ $# -gt 0 ]]; do
        case $1 in
            --verify-only)
                VERIFY_ONLY=true
                shift
                ;;
            --skip-redis)
                SKIP_REDIS=true
                shift
                ;;
            --verbose)
                VERBOSE=true
                shift
                ;;
            -h|--help)
                show_usage
                exit 0
                ;;
            *)
                echo "Unknown option: $1"
                show_usage
                exit 2
                ;;
        esac
    done

    # Banner
    clear
    echo -e "${BLUE}"
    echo "╔════════════════════════════════════════════════════════════╗"
    echo "║   Acuity Scheduling Manager - Setup & Initialization       ║"
    echo "╚════════════════════════════════════════════════════════════╝"
    echo -e "${NC}"

    # Run checks
    if ! check_python; then
        show_summary "failure"
        exit 1
    fi

    if ! check_environment_file; then
        show_summary "failure"
        exit 1
    fi

    load_credentials

    if ! check_credentials; then
        show_summary "failure"
        exit 1
    fi

    if [ "$VERIFY_ONLY" = true ]; then
        if test_api_connectivity; then
            show_summary "success"
            exit 0
        else
            show_summary "failure"
            exit 1
        fi
    fi

    # Full setup
    if ! install_dependencies; then
        show_summary "failure"
        exit 1
    fi

    if ! test_api_connectivity; then
        show_summary "failure"
        exit 1
    fi

    check_redis

    if ! verify_directory_structure; then
        show_summary "failure"
        exit 1
    fi

    show_summary "success"
    exit 0
}

# Run main
main "$@"
