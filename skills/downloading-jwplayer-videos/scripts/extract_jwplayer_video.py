#!/usr/bin/env python3
"""
JWPlayer Video Extractor

Extracts video URLs from web pages using JWPlayer by accessing the JWPlayer
JavaScript API. Falls back to browser automation if direct yt-dlp extraction fails.

Usage:
    python extract_jwplayer_video.py <url> [--download] [--output <filename>]

Requirements:
    - yt-dlp
    - mcp__plugin_superpowers-chrome (for browser automation)

Author: Generated by Claude Code
"""

import sys
import json
import subprocess
import argparse
from pathlib import Path


def try_ytdlp_direct(url: str) -> dict:
    """
    Try direct yt-dlp extraction first (fast path).

    Returns:
        dict: {
            'success': bool,
            'url': str (if success),
            'error': str (if failed)
        }
    """
    print(f"🔍 Trying direct yt-dlp extraction...")
    try:
        result = subprocess.run(
            ["yt-dlp", "--dump-json", url],
            capture_output=True,
            text=True,
            timeout=30
        )

        if result.returncode == 0:
            data = json.loads(result.stdout)
            return {
                'success': True,
                'url': data.get('url'),
                'title': data.get('title'),
                'format': data.get('format')
            }
        else:
            return {
                'success': False,
                'error': result.stderr
            }
    except subprocess.TimeoutExpired:
        return {'success': False, 'error': 'yt-dlp timeout'}
    except Exception as e:
        return {'success': False, 'error': str(e)}


def extract_jwplayer_urls_browser(url: str) -> dict:
    """
    Extract JWPlayer video URLs using browser automation.

    This function expects to be called from Claude Code with access to
    the mcp__plugin_superpowers-chrome_chrome__use_browser tool.

    Returns:
        dict: {
            'success': bool,
            'videos': list of dicts with 'player_id', 'file', 'type'
            'error': str (if failed)
        }
    """
    print(f"🌐 Using browser automation to extract JWPlayer URLs...")

    # This is a reference implementation that shows the extraction logic
    # In practice, Claude Code will use the browser tool directly

    extraction_script = """
// Find all JWPlayer instances on the page
const playerDivs = document.querySelectorAll('[id^="jwplayer-"]');
const results = [];

for (const div of playerDivs) {
    const playerId = div.id;
    try {
        // Access JWPlayer instance
        const player = jwplayer(playerId);

        // Get playlist (contains video sources)
        const playlist = player.getPlaylist();

        if (playlist && playlist.length > 0) {
            playlist.forEach((item, index) => {
                if (item.sources && item.sources.length > 0) {
                    item.sources.forEach(source => {
                        results.push({
                            player_id: playerId,
                            playlist_index: index,
                            title: item.title || 'Untitled',
                            file: source.file,
                            type: source.type,
                            label: source.label || 'default'
                        });
                    });
                }
            });
        }
    } catch (e) {
        console.error(`Failed to access player ${playerId}:`, e);
    }
}

return results;
"""

    return {
        'success': False,
        'error': 'This function should be called from Claude Code with browser automation',
        'extraction_script': extraction_script
    }


def download_video(video_url: str, output_filename: str = None) -> dict:
    """
    Download video using yt-dlp.

    Args:
        video_url: Direct video URL (HLS manifest or MP4)
        output_filename: Optional output filename (without extension)

    Returns:
        dict: {'success': bool, 'output': str, 'error': str}
    """
    print(f"⬇️  Downloading video...")

    cmd = ["yt-dlp"]

    if output_filename:
        cmd.extend(["-o", f"{output_filename}.%(ext)s"])
    else:
        cmd.extend(["-o", "video.%(ext)s"])

    cmd.append(video_url)

    try:
        result = subprocess.run(cmd, capture_output=True, text=True)

        if result.returncode == 0:
            return {
                'success': True,
                'output': result.stdout
            }
        else:
            return {
                'success': False,
                'error': result.stderr
            }
    except Exception as e:
        return {
            'success': False,
            'error': str(e)
        }


def main():
    parser = argparse.ArgumentParser(
        description='Extract and download videos from JWPlayer-enabled pages'
    )
    parser.add_argument('url', help='URL of the page with video')
    parser.add_argument('--download', action='store_true',
                       help='Download the video after extraction')
    parser.add_argument('--output', '-o', help='Output filename (without extension)')

    args = parser.parse_args()

    print(f"🎬 JWPlayer Video Extractor")
    print(f"📄 URL: {args.url}\n")

    # Step 1: Try direct yt-dlp first
    direct_result = try_ytdlp_direct(args.url)

    if direct_result['success']:
        print(f"✅ Direct extraction successful!")
        print(f"   Title: {direct_result.get('title', 'N/A')}")
        print(f"   URL: {direct_result['url']}")

        if args.download:
            download_result = download_video(direct_result['url'], args.output)
            if download_result['success']:
                print(f"✅ Download complete!")
            else:
                print(f"❌ Download failed: {download_result['error']}")

        return 0

    # Step 2: Direct extraction failed, use browser automation
    print(f"⚠️  Direct extraction failed: {direct_result.get('error', 'Unknown error')}")
    print(f"📌 Falling back to browser automation...")
    print(f"\n⚠️  This script requires Claude Code with browser automation.")
    print(f"   Use the 'downloading-jwplayer-videos' skill for full automation.\n")

    browser_result = extract_jwplayer_urls_browser(args.url)
    print(f"\n📋 Extraction script for browser automation:")
    print(f"```javascript")
    print(browser_result['extraction_script'])
    print(f"```")

    return 1


if __name__ == '__main__':
    sys.exit(main())
